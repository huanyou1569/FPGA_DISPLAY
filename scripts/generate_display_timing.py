"""Generate the matching PL/PS display contract and Q15 angle ROM (no build/hardware)."""
import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLOCK_HZ = 125_000_000
TARGET_RPS = 15
SLICES = 120
assert SLICES % 4 == 0 and SLICES <= 128

def outputs():
    constants = {"CLOCK_HZ": CLOCK_HZ, "TARGET_RPS": TARGET_RPS, "ANGLE_SLICES": SLICES}
    v = "// Generated by scripts/generate_display_timing.py\n`ifndef VX_DISPLAY_TIMING_VH\n`define VX_DISPLAY_TIMING_VH\n"
    c = "/* Generated by scripts/generate_display_timing.py */\n#ifndef VX_DISPLAY_TIMING_H\n#define VX_DISPLAY_TIMING_H\n"
    for name, value in constants.items():
        v += f"`define VX_{name} {value}\n"
        c += f"#define VX_{name} {value}u\n"
    v += "`endif\n"
    c += "#define VX_SLICE_PERIOD_US(period) ((period) / ((VX_CLOCK_HZ / 1000000u) * VX_ANGLE_SLICES))\n#endif\n"
    rom = '''// Generated by scripts/generate_display_timing.py.
// 120 distinct angles, 3 degrees each; synchronous Q15 cosine/sine.
// The PC JH angle remains 0..99 (fraction of a turn), independent of slices.
module sincos_rom (
    input wire clk,
    input wire [7:0] phase,
    output reg signed [15:0] cos_v,
    output reg signed [15:0] sin_v
);
    reg signed [15:0] cos_tab [0:127];
    integer k;
    initial begin
        for (k=0; k<128; k=k+1) cos_tab[k] = 16'sd0;
'''
    for i in range(SLICES):
        value = round(math.cos(2 * math.pi * i / SLICES) * 32767)
        literal = f"-16'sd{-value}" if value < 0 else f"16'sd{value}"
        rom += f"        cos_tab[{i}] = {literal};\n"
    rom += f'''    end
    wire [6:0] idx = phase[6:0];
    wire [6:0] si = (idx < 7'd{SLICES//4}) ? (idx + 7'd{3*SLICES//4}) : (idx - 7'd{SLICES//4});
    always @(posedge clk) begin
        cos_v <= cos_tab[idx];
        sin_v <= cos_tab[si];
    end
endmodule
'''
    return {ROOT / "test.srcs/sources_1/new/display_timing.vh": v,
            ROOT / "software/brush_app/vx_display_timing.h": c,
            ROOT / "test.srcs/sources_1/new/sincos_rom.v": rom}

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            assert path.read_text(encoding="utf-8") == content, f"Generated file is stale: {path}"
        else:
            path.write_text(content, encoding="utf-8")
    print(f"TIMING_CONTRACT_PASS: {TARGET_RPS} rps, {SLICES} slices/rev, {TARGET_RPS*SLICES} slices/s")
